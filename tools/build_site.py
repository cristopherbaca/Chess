"""Build a frontend-only GitHub Pages artifact; never copy the workspace wholesale."""
import argparse
import json
import os
from pathlib import Path
import shutil
from urllib.parse import urlsplit

ROOT = Path(__file__).resolve().parents[1]


def public_api_url(value):
    value = value.strip().rstrip('/')
    if not value:
        return ''
    parsed = urlsplit(value)
    if (parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password
            or parsed.query or parsed.fragment or any(c.isspace() for c in value)
            or any(c in value for c in '<>"\'\\;')):
        raise ValueError('The public API URL must use HTTPS without credentials, query or fragment.')
    return value


def build(root=ROOT, api_url=''):
    root = Path(root).resolve()
    output = root / '_site'
    api_url = public_api_url(api_url)
    if output.is_symlink():
        raise ValueError('_site cannot be a symlink')
    if output.exists():
        if not (output / '.chess-site-artifact').is_file():
            raise ValueError('Refusing to overwrite an unrecognized _site directory')
        shutil.rmtree(output)
    files = [root / 'index.html', root / 'LICENSES.md', root / 'vendor/chess.js', root / 'vendor/LICENSE-chess.md']
    for folder, extensions in (('js', {'.js'}), ('css', {'.css'}), ('assets/pieces', {'.svg'})):
        files.extend(p for p in (root / folder).rglob('*') if p.is_file() and p.suffix in extensions)
    files.extend(root / 'assets/pieces' / name for name in ('LICENSE', 'README.md'))
    for path in files:
        if path.is_symlink() or not path.resolve().is_relative_to(root):
            raise ValueError('Public assets cannot point outside the repository or use symlinks')
        target = output / path.relative_to(root)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
    (output / 'js/public-config.js').write_text('export const PUBLIC_API_URL = ' + json.dumps(api_url) + ';\n')
    index = output / 'index.html'
    html = index.read_text()
    connect = "'self'" + (' ' + urlsplit(api_url).scheme + '://' + urlsplit(api_url).netloc if api_url else '')
    html = html.replace("connect-src 'self' https: http://localhost:8000 http://127.0.0.1:8000", 'connect-src ' + connect + ' https://chess-api.com')
    index.write_text(html)
    (output / '.nojekyll').touch()
    (output / '.chess-site-artifact').write_text('Generated by tools/build_site.py; safe to rebuild.\n')
    return output


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--api-url', default=os.environ.get('CHESS_PUBLIC_API_URL', ''))
    args = parser.parse_args()
    print(build(api_url=args.api_url))
