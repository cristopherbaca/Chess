"""Bundle canonical engine modules into the standalone Colab worker source.

Run after editing chess_ai/*.py. --check detects a stale notebook bundle.
The generated package uses a content-derived namespace to isolate model versions.
"""
import argparse
import ast
import base64
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parents[1]
MODULES = ('board', 'evaluation', 'search', 'neural', 'inference', 'storage', 'runtime', 'matches', 'strength', 'training', 'notebook_bridge',
           'datasets', 'validation_cases', 'full_pipeline')
BEGIN = '# BEGIN GENERATED CHESS ENGINE BUNDLE\n'
END = '# END GENERATED CHESS ENGINE BUNDLE\n'


def bundle_source():
    sources = {name: (ROOT / 'chess_ai' / (name + '.py')).read_text() for name in MODULES}
    data = json.dumps(sources, sort_keys=True).encode()
    digest = hashlib.sha256(data).hexdigest()
    payload = base64.b64encode(zlib.compress(data, 9)).decode()
    return BEGIN + f'''# Generated by tools/sync_engine.py; edit chess_ai/ instead.
def _install_chess_engine_bundle():
    import base64, zlib, json, sys, types
    name = 'chess_ai_bundle_{digest[:16]}'
    if name in sys.modules:
        return sys.modules[name]
    sources = json.loads(zlib.decompress(base64.b64decode('{payload}')))
    package = types.ModuleType(name)
    package.__path__ = []
    package.source_sha256 = '{digest}'
    sys.modules[name] = package
    for short in {MODULES!r}:
        module = types.ModuleType(name + '.' + short)
        module.__package__ = name
        sys.modules[module.__name__] = module
        setattr(package, short, module)
        exec(compile(sources[short], '<bundled-chess-ai/' + short + '.py>', 'exec'), module.__dict__)
    return package
_CHESS_ENGINE_PACKAGE = _install_chess_engine_bundle()
''' + END


def sync(check=False):
    path = ROOT / 'vendor/train.ipynb'
    book = json.loads(path.read_text())
    cell = next(c for c in book['cells'] if c['id'] == 'train-engine')
    code = ''.join(cell['source'])
    assignment = next(n for n in ast.parse(code).body if isinstance(n, ast.Assign)
                      and isinstance(n.targets[0], ast.Name) and n.targets[0].id == 'CORE_SOURCE')
    source = ast.literal_eval(assignment.value)
    generated = bundle_source()
    if BEGIN in source:
        start, end = source.index(BEGIN), source.index(END) + len(END)
        updated = source[:start] + generated + source[end:]
    else:
        updated = source + '\n' + generated
    if check:
        if source != updated:
            raise SystemExit('Stale notebook engine bundle. Run python tools/sync_engine.py')
        sync_security(check=True)
        sync_inference(check=True)
        print('Notebook engine, inference and API security bundles match canonical modules.')
        return
    literal = ast.get_source_segment(code, assignment.value)
    assert "'''" not in updated
    code = code.replace(literal, "r'''" + updated + "'''", 1)
    cell['source'] = code.splitlines(keepends=True)
    path.write_text(json.dumps(book, ensure_ascii=False, indent=1) + '\n')
    sync_security()
    sync_inference()
    print('Updated standalone notebook bundle; preserved notebook outputs/settings.')


def sync_security(check=False):
    path = ROOT / 'vendor/deploy.ipynb'
    book = json.loads(path.read_text())
    cell = next(c for c in book['cells'] if c['id'] == 'phase3-app')
    code = ''.join(cell['source'])
    begin, end = '# BEGIN GENERATED API SECURITY\n', '# END GENERATED API SECURITY\n'
    source = (ROOT / 'chess_ai/api_security.py').read_text()
    assert "'''" not in source
    generated = begin + "SECURITY_SOURCE = r'''" + source + "'''\n" + end
    if begin in code:
        start, stop = code.index(begin), code.index(end) + len(end)
        updated = code[:start] + generated + code[stop:]
    else:
        title, rest = code.split('\n', 1)
        updated = title + '\n' + generated + rest
    if check:
        if code != updated:
            raise SystemExit('Stale API security bundle. Run python tools/sync_engine.py')
    else:
        cell['source'] = updated.splitlines(keepends=True)
        path.write_text(json.dumps(book, ensure_ascii=False, indent=1) + '\n')


def sync_inference(check=False):
    path = ROOT / 'vendor/deploy.ipynb'
    book = json.loads(path.read_text())
    cell = next(c for c in book['cells'] if c['id'] == 'phase3-load')
    code = ''.join(cell['source'])
    begin, end = '# BEGIN GENERATED INFERENCE SUPPORT\n', '# END GENERATED INFERENCE SUPPORT\n'
    source = (ROOT / 'chess_ai/inference.py').read_text()
    assert "'''" not in source
    generated = begin + "INFERENCE_SOURCE = r'''" + source + "'''\n" + end
    if begin in code:
        start, stop = code.index(begin), code.index(end) + len(end)
        updated = code[:start] + generated + code[stop:]
    else:
        title, rest = code.split('\n', 1)
        updated = title + '\n' + generated + rest
    if check:
        if code != updated:
            raise SystemExit('Stale inference support. Run python tools/sync_engine.py')
    else:
        cell['source'] = updated.splitlines(keepends=True)
        path.write_text(json.dumps(book, ensure_ascii=False, indent=1) + '\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    sync(parser.parse_args().check)
